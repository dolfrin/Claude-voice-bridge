"""Everything the bot says to the user, in English and Lithuanian.

``BOT_LANGUAGE`` picks the language once at start-up (:func:`set_language`);
:func:`t` returns a text by key, filled in with ``str.format`` fields. Both
catalogs must have the same keys and fields -- ``tests/test_i18n.py`` fails
otherwise, so a text cannot be added in one language only.

Text written for the model (the note appended to live-session messages) is
not here: it stays in English, which every model reads.
"""

from __future__ import annotations

# ponytail: one process-wide language; per-chat languages would need the
# language passed along with every message.
_language = "en"


def set_language(language: str) -> None:
    global _language
    if language not in CATALOGS:
        raise ValueError(f"unknown language {language!r}")
    _language = language


def language() -> str:
    return _language


def t(key: str, **fields) -> str:
    """The text for *key* in the current language."""
    return CATALOGS[_language][key].format(**fields)


EN: dict[str, str] = {}
LT: dict[str, str] = {}
CATALOGS = {"en": EN, "lt": LT}


